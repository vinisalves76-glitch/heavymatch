-- 2. Only verified sellers/admins may upload directly to vehicle-photos.
-- 3. Uploaded objects must use the uploader's UUID as the first folder.
-- Signed upload URLs generated by the authorized backend continue to work.

BEGIN;

REVOKE ALL PRIVILEGES ON TABLE public.profiles FROM anon, authenticated;
GRANT SELECT ON TABLE public.profiles TO authenticated;
GRANT UPDATE (full_name, phone) ON TABLE public.profiles TO authenticated;

DROP POLICY IF EXISTS profile_insert_own ON public.profiles;

DROP POLICY IF EXISTS "Vendedores autenticados podem enviar fotos xzv0aq_0" ON storage.objects;
DROP POLICY IF EXISTS vehicle_photos_commercial_upload ON storage.objects;
CREATE POLICY vehicle_photos_commercial_upload
ON storage.objects FOR INSERT TO authenticated
WITH CHECK (
  bucket_id = 'vehicle-photos'
  AND (storage.foldername(name))[1] = (SELECT auth.uid())::text
  AND EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = (SELECT auth.uid())
      AND p.role IN ('seller', 'admin')
  )
);

DROP POLICY IF EXISTS "Usuários autenticados podem visualizar fotos xzv0aq_0" ON storage.objects;
DROP POLICY IF EXISTS vehicle_photos_owner_select ON storage.objects;
CREATE POLICY vehicle_photos_owner_select
ON storage.objects FOR SELECT TO authenticated
USING (
  bucket_id = 'vehicle-photos'
  AND (storage.foldername(name))[1] = (SELECT auth.uid())::text
);

COMMIT;

